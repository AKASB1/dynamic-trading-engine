"""The experiments S1 to S7 (and SENS): evaluation jobs from the frozen configurations, the
non-loop experiments (exact references, multi-period control, execution), and the aggregates.

Everything the evaluation runs is listed in ``frozen.json`` (generated by ``freeze`` from the
committed registry and the tuned configurations); the evaluation refuses anything else.
"""

from __future__ import annotations

