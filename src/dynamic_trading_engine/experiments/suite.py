from dynamic_trading_engine.analytics.stats import mean_ci, paired
from dynamic_trading_engine.contracts.canonical import config_hash, write_json
from dynamic_trading_engine.experiments import protocol as PT
from dynamic_trading_engine.experiments import registry as R
from dynamic_trading_engine.experiments.criterion import criterion, criterion_segment
from dynamic_trading_engine.experiments.jobs import Job, run_job
from dynamic_trading_engine.experiments.output import write_csv
from dynamic_trading_engine.experiments.runner import manifest, run_parallel

LOOP_EXPERIMENTS = ("S2", "S2b", "S3", "S4", "S5", "S6c", "S8", "SENS")


def _seeds(reg, key, quick):
    return reg["seeds"]["dev_quick"] if quick else reg["seeds"][key]


def _label(spec, quick, extra=""):
    parts = []
    if quick:
        parts.append("QUICK")
    if R.is_oracle(spec):
        parts.append("ORACLE")
    if extra:
        parts.append(extra)
    return "+".join(parts)


def plan(reg: dict, tuned: dict, quick: bool, only: tuple[str, ...] | None = None) -> list[Job]:
    """Every loop job of the evaluation (S2, S2b, S3, S4, S5, S6c, SENS)."""
    main = reg["markets"]["quick_main" if quick else "main"]
    shift = reg["markets"]["quick_shift" if quick else "shift"]
    at = reg["S5"]["quick_at_bar" if quick else "at_bar"]
    specs = PT.frozen_specs(reg, tuned)
    jobs: list[Job] = []

    def add(
        exp,
        variant,
        spec,
        market,
        seeds,
        loop=None,
        costs=None,
        extra_label="",
        segment=0,
        extra=None,
        log_first=True,
    ):
        if only and exp not in only:
            return
        h = PT.run_config_hash(spec, market, loop, costs)
        for i, s in enumerate(seeds):
            log_dir = ""
            if log_first and i == 0:
                log_dir = R.path(
                    R.OUTPUTS_DIR,
                    "quick" if quick else "full",
                    "logs",
                    exp,
                    variant.replace("|", "_"),
                )
            jobs.append(
                Job(
                    exp,
                    variant,
                    spec,
                    market,
                    s,
                    loop or {},
                    costs or {},
                    _label(spec, quick, extra_label),
                    segment,
                    log_dir,
                    h,
                    extra or {},
                )
            )

    s2 = _seeds(reg, "S2", quick)
    for name in reg["s2_order"]:
        add("S2", name, specs[name], main, s2, segment=at)
    lad = reg["ladder"]
    for rung in lad["rungs"]:
        for ci in [False, True] if lad["cost_ignorant"] else [False]:
            key = f"{rung['id']}|{int(ci)}"
            spec = tuned["ladder"][key]["spec"]
            add(
                "S2b",
                f"MV_{rung['id']}{'_NC' if ci else ''}",
                spec,
                main,
                s2,
                extra={"measure_quality": True},
            )
    mv = specs[reg["S3"]["base"]]
    s3 = _seeds(reg, "S3", quick)
    c3 = reg["S3"]
    # S3 varies one thing at a time around the tuned MV at the parity setting (cost_scale 1);
    # the tuned MV itself (its own cost_scale) is a row for reference
    parity = copy.deepcopy(mv)
    parity["optimizer"]["cost_scale"] = 1.0
    add("S3", "tuned", mv, main, s3)
    for cs in c3["cost_scale"]:
        sp = copy.deepcopy(parity)
        sp["optimizer"]["cost_scale"] = cs
        add("S3", "parity" if cs == 1.0 else f"cost_scale={cs:g}", sp, main, s3)
    for tv in c3["turnover"]:
        if tv is None:
            continue
        sp = copy.deepcopy(parity)
        sp["optimizer"]["turnover"] = tv
        add("S3", f"turnover={tv:g}", sp, main, s3)
    for k in c3["rebalance_every"]:
        if k != reg["loop"]["rebalance_every"]:
            add("S3", f"rebalance={k}", parity, main, s3, loop={"rebalance_every": k})
    for b in c3["books"]:
        if b == "LS":
            continue
        sp = copy.deepcopy(parity)
        if b == "LO":
            sp["book"] = "LO"
        elif b == "LS_sector":
            sp["optimizer"]["sector_max"] = c3["sector_max"]
        elif b == "LS_beta":
            sp["optimizer"]["beta_band"] = list(c3["beta_band"])
        add("S3", f"book={b}", sp, main, s3)
    # S4: MINVAR with each risk model and window
    c4 = reg["S4"]
    s4 = _seeds(reg, "S4", quick)
    markets4 = [main] if quick else c4["markets"]
    rules = c4["quick_window_rule"] if quick else c4["window_rule"]
    from dynamic_trading_engine.market.config import load_market_config

    for mk in markets4:
        n = load_market_config(mk).n_instruments
        for rule in rules:
            W = 250 if rule == "250" else (2 * n if rule == "2n" else n)
            for rm in c4["risk_models"]:
                sp = R.base_spec(reg, "MINVAR")
                sp.update({"risk": rm, "window": W, "hl": W / 4.0, "strategy_id": f"MINVAR_{rm}"})
                add(
                    "S4",
                    f"{mk}|{rule}|{rm}",
                    sp,
                    mk,
                    s4,
                    extra={"s4_probe": True, "window": W, "n_over_W": n / W},
                    log_first=False,
                )
    # S5: the frozen S2 configurations on the shift market (+ the RETUNED bound)
    s5 = _seeds(reg, "S5", quick)
    for name in reg["s2_order"]:
        add("S5", name, specs[name], shift, s5, segment=at)
    for name, r in sorted(tuned["retuned"].items()):
        add(
            "S5",
            f"{name}_RETUNED",
            r["spec"],
            shift,
            s5,
            extra_label="RETUNED",
            segment=at,
            log_first=False,
        )
    # S6(c): MPC horizons with the tuned MV configuration and delta 1
    s6 = _seeds(reg, "S6", quick)
    for H in reg["S6"]["c"]["H"]:
        sp = copy.deepcopy(mv)
        sp["optimizer"]["name"] = "mpc"
        sp["optimizer"]["H"] = H
        sp["optimizer"]["delta"] = reg["S6"]["c"]["delta"]
        sp["strategy_id"] = f"MPC_H{H}"
        add("S6c", f"H={H}", sp, main, s6)
    # S8: post-hoc re-costing of the tuned MV's parent orders at three capital levels
    s8 = _seeds(reg, "S8", quick)
    for cap in reg["S8"]["capital"]:
        add(
            "S8",
            f"capital={cap:g}",
            mv,
            main,
            s8,
            loop={"initial_cash": float(cap)},
            extra={"s8_recost": True},
            log_first=False,
        )
    # SENS: simulator costs at half and double (the optimizer's model unchanged), the stress market
    if True:  # SENS runs in both modes (quick: the tiny market stands in for stress)
        sens = _seeds(reg, "SENS", quick)
        for mult in reg["SENS"]["cost_mult"]:
            costs = _scaled_costs(mult)
            for name in reg["s2_order"]:
                sp = copy.deepcopy(specs[name])
                # c(z) is linear in the cost coefficients: dividing cost_scale by the multiplier
                # keeps the optimizer's own cost model at the parity setting
                sp["optimizer"]["cost_scale"] = sp["optimizer"].get("cost_scale", 1.0) / mult
                add("SENS", f"cost_x{mult:g}|{name}", sp, main, sens, costs=costs, log_first=False)
        stress = main if quick else reg["SENS"]["stress_market"]
        for name in reg["s2_order"]:
            add("SENS", f"stress|{name}", specs[name], stress, sens, log_first=False)
    return jobs


def _scaled_costs(mult: float) -> dict:
    from dynamic_trading_engine.contracts.costs import CostConfig

    c = CostConfig().scaled(mult)
    return {
        "commission_bps": c.commission_bps,
        "half_spread_bps": c.half_spread_bps,
        "impact": {"model": c.impact.model, "y": c.impact.y},
    }


def nonloop_entries(reg: dict, quick: bool) -> list[dict]:
    out = []
    for key in ("S1", "S6", "S7"):
        out.append(
            {
                "id": f"{key}/registry",
                "experiment": key,
                "variant": "registry",
                "hash": config_hash(reg[key]),
            }
        )
    return out


def freeze(reg: dict, quick: bool) -> str:
    tuned = PT.load_tuned(reg, quick)
    entries = {}
    for j in plan(reg, tuned, quick):
        entries[f"{j.experiment}/{j.variant}"] = {
            "id": f"{j.experiment}/{j.variant}",
            "experiment": j.experiment,
            "variant": j.variant,
            "market": j.market,
            "spec": j.spec,
            "loop": j.loop,
            "costs": j.costs,
            "hash": j.config_hash,
        }
    return PT.write_frozen(list(entries.values()) + nonloop_entries(reg, quick), quick)


# ---------------------------------------------------------------- aggregation


def _by(rows, exp):
    out = {}
    for r in rows:
        if r["experiment"] == exp:
            out.setdefault(r["variant"], {})[r["seed"]] = r
    return out


def agg_s2(reg, rows):
    by = _by(rows, "S2")
    order = reg["s2_order"]
    summ = []
    for name in order:
        rs = by[name]
        seeds = sorted(rs)
        m, ci, n = mean_ci([criterion(rs[s]) for s in seeds])
        row = {
            "strategy": name,
            "label": rs[seeds[0]]["label"],
            "n_seeds": n,
            "ce_ann_mean": m,
            "ce_ann_ci95": ci,
        }
        for k in (
            "sharpe",
            "sharpe_gross",
            "ann_return",
            "ann_vol",
            "max_drawdown",
            "cvar95",
            "turnover",
            "cost_drag",
            "gross_exposure",
            "net_exposure",
            "hold_frac",
            "flat_frac",
        ):
            row[k] = mean_ci([rs[s][k] for s in seeds])[0]
        row["n_inaccurate"] = sum(rs[s]["n_inaccurate"] for s in seeds)
        row["n_failed"] = sum(rs[s]["n_failed"] for s in seeds)
        row["max_violation"] = max(rs[s]["max_violation"] for s in seeds)
        summ.append(row)
    pair = []
    for base in reg["baselines"]:
        ref = {s: criterion(r) for s, r in by[base].items()}
        for name in order:
            if name == base:
                continue
            p = paired(ref, {s: criterion(r) for s, r in by[name].items()})
            pair.append({"strategy": name, "baseline": base, **p})
    # DSR: the 8 registered strategies of the table are the trials on each seed (CASH is a
    # reference, not a trial)
    trials = reg["s2_registered"]
    seeds = sorted(by[trials[0]])
    dsr_rows = []
    for s in seeds:
        srs = [by[n][s]["sr_bar"] for n in trials]
        V = float(np.var(srs, ddof=1))
        best = max(trials, key=lambda n: (by[n][s]["sr_bar"], -trials.index(n)))
        r = by[best][s]
        d = dsr(r["sr_bar"], r["n_bars"], r["skew"], r["kurt"], V, len(trials))
        dsr_rows.append(
            {
                "seed": s,
                "selected_by_sharpe": best,
                "sr_bar": r["sr_bar"],
                "V": V,
                "N": len(trials),
                "dsr": d,
                "dsr_gt_0.95": d > 0.95,
            }
        )
    return summ, pair, dsr_rows


def agg_simple(rows, exp, ref_variant=None, order=None, ppy=252):
    by = _by(rows, exp)
    names = order or sorted(by)
    out = []
    for v in names:
        if v not in by:
            continue
        rs = by[v]
        seeds = sorted(rs)
        m, ci, n = mean_ci([criterion(rs[s]) for s in seeds])
        row = {
            "variant": v,
            "label": rs[seeds[0]]["label"],
            "n_seeds": n,
            "ce_ann_mean": m,
            "ce_ann_ci95": ci,
        }
        for k in (
            "sharpe",
            "ann_vol",
            "turnover",
            "cost_drag",
            "gross_exposure",
            "hold_frac",
            "flat_frac",
            "forecast_quality",
            "frobenius_rel",
            "calibration",
            "share_below_sample",
            "n_over_W",
            "window",
        ):
            if k in rs[seeds[0]]:
                row[k] = mean_ci([rs[s][k] for s in seeds])[0]
                if k in ("forecast_quality", "ann_vol"):
                    row[k + "_ci95"] = mean_ci([rs[s][k] for s in seeds])[1]
        if ref_variant and ref_variant in by and v != ref_variant:
            p = paired(
                {s: criterion(r) for s, r in by[ref_variant].items()},
                {s: criterion(r) for s, r in rs.items()},
            )
            row.update(
                {
                    f"diff_vs_{ref_variant}": p["diff_mean"],
                    "diff_ci95": p["diff_ci"],
                    "wins": p["wins"],
                    "ties": p["ties"],
                    "losses": p["losses"],
                }
            )
        out.append(row)
    return out


def agg_s5(reg, rows):
    base = _by(rows, "S2")
    sh = _by(rows, "S5")
    out = []
    for v in sorted(
        sh, key=lambda x: (x.endswith("_RETUNED"), reg["s2_order"].index(x.replace("_RETUNED", "")))
    ):
        name = v.replace("_RETUNED", "")
        seeds = sorted(sh[v])
        post_shift = {s: criterion_segment(sh[v][s], "post") for s in seeds}
        pre_shift = {s: criterion_segment(sh[v][s], "pre") for s in seeds}
        row = {
            "strategy": v,
            "label": sh[v][seeds[0]]["label"],
            "n_seeds": len(seeds),
            "ce_post_shift_mean": mean_ci(list(post_shift.values()))[0],
            "ce_post_shift_ci95": mean_ci(list(post_shift.values()))[1],
        }
        if not v.endswith("_RETUNED"):
            post_base = {
                s: criterion_segment(base[name][s], "post")
                for s in seeds
                if s in base.get(name, {})
            }
            eff = paired(post_base, post_shift)
            row.update(
                {
                    "effect_mean": eff["diff_mean"],
                    "effect_ci95": eff["diff_ci"],
                    "ce_post_base_mean": mean_ci(list(post_base.values()))[0],
                }
            )
            seg = paired(pre_shift, post_shift)
            row.update(
                {
                    "after_minus_before_mean": seg["diff_mean"],
                    "after_minus_before_ci95": seg["diff_ci"],
                }
            )
        for ref in ("EW", "MV"):
            if ref in sh and v != ref:
                p = paired({s: criterion_segment(sh[ref][s], "post") for s in sh[ref]}, post_shift)
                row[f"post_diff_vs_{ref}"] = p["diff_mean"]
                row[f"post_diff_vs_{ref}_ci95"] = p["diff_ci"]
                row[f"post_wtl_vs_{ref}"] = f"{p['wins']}/{p['ties']}/{p['losses']}"
        out.append(row)
    return out


def agg_s8(rows):
    by = _by(rows, "S8")
    out = []
    for v in sorted(by, key=lambda x: float(x.split("=")[1])):
        rs = [by[v][s] for s in sorted(by[v])]
        row = {
            "variant": v,
            "n_seeds": len(rs),
            "orders_per_run": float(np.mean([r["s8_orders"] for r in rs])),
        }
        for k in (
            "s8_loop_cost_bps",
            "s8_market_cost_bps",
            "s8_twap_cost_bps",
            "s8_vwap_cost_bps",
            "s8_loop_capped_share",
            "s8_market_capped_share",
        ):
            m, ci, _n = mean_ci([r[k] for r in rs])
            row[k.replace("s8_", "")] = m
            row[k.replace("s8_", "") + "_ci95"] = ci
        out.append(row)
    return out


def agg_sens(reg, rows):
    out = []
    s2 = _by(rows, "S2")
    for g in reg["SENS"]["gamma_ce"]:
        for name in reg["s2_order"]:
            vals = [ce_ann(r["mean"], r["var"], 252, g) for r in s2[name].values()]
            m, ci, n = mean_ci(vals)
            out.append(
                {
                    "sensitivity": f"gamma_ce={g:g}",
                    "strategy": name,
                    "ce_ann_mean": m,
                    "ce_ann_ci95": ci,
                }
            )
    sens = _by(rows, "SENS")
    for v in sorted(sens):
        kind, name = v.split("|")
        vals = [criterion(r) for r in sens[v].values()]
        m, ci, n = mean_ci(vals)
        out.append({"sensitivity": kind, "strategy": name, "ce_ann_mean": m, "ce_ann_ci95": ci})
    return out


# ---------------------------------------------------------------- run everything


def run_all(
    reg: dict, quick: bool, workers: int, out_dir: str | None = None, only=None, log=print
) -> dict:
    t0 = time.perf_counter()
    out_dir = out_dir or (
        R.path(R.OUTPUTS_DIR, "quick", "results") if quick else R.path(R.RESULTS_DIR)
    )
    os.makedirs(out_dir, exist_ok=True)
    tuned = PT.load_tuned(reg, quick)
    jobs = plan(reg, tuned, quick, only)
    PT.check_eval_seeds(sorted({j.seed for j in jobs}), quick)
    PT.check_frozen(jobs, quick)
    jobs.sort(key=lambda j: (j.market, j.seed, j.experiment, j.variant))
    log(f"evaluation: {len(jobs)} loop runs with {workers} workers")
    rows = run_parallel(run_job, jobs, workers)
    rows.sort(key=lambda r: (r["experiment"], r["variant"], r["seed"]))
    tag = "_quick" if quick else ""
    first = ["experiment", "variant", "seed", "market", "label", "config_hash"]
    files = {}

    def w(name, data, cols):
        p = os.path.join(out_dir, f"{name}{tag}.csv")
        write_csv(p, data, cols)
        files[name] = p

    w("runs", rows, first)
    if not only or "S2" in only:
        summ, pair, dsr_rows = agg_s2(reg, rows)
        w("s2_summary", summ, ["strategy", "label", "n_seeds", "ce_ann_mean", "ce_ann_ci95"])
        w("s2_paired", pair, ["strategy", "baseline"])
        w("s2_dsr", dsr_rows, ["seed"])
        lad_order = [f"MV_{r['id']}{s}" for r in reg["ladder"]["rungs"] for s in ("", "_NC")]
        w("s2b_ladder", agg_simple(rows, "S2b", order=lad_order), ["variant", "label"])
    for exp, ref in (("S3", "parity"), ("S4", None), ("S6c", "H=1")):
        if not only or exp in only:
            # tables keep the order of the registry (the plan's order)
            order = list(dict.fromkeys(j.variant for j in plan(reg, tuned, quick, (exp,))))
            w(exp.lower(), agg_simple(rows, exp, ref, order=order), ["variant", "label"])
    if not only or "S5" in only:
        w("s5_shift", agg_s5(reg, rows), ["strategy", "label"])
    if not only or "SENS" in only:
        w("sens", agg_sens(reg, rows), ["sensitivity", "strategy"])
    if not only or "S8" in only:
        w("s8_recost", agg_s8(rows), ["variant"])
    from dynamic_trading_engine.experiments import nonloop

    # the non-loop experiments run on registry sections whose hashes the freeze recorded
    frozen = PT.load_frozen_hashes(quick)
    for key in ("S1", "S6", "S7"):
        if config_hash(reg[key]) not in frozen:
            raise PT.ProtocolError(f"the {key} section of the registry is not frozen")
    for name, fn in (
        ("S1", nonloop.s1),
        ("S6a", nonloop.s6a),
        ("S6b", nonloop.s6b),
        ("S7", nonloop.s7),
    ):
        if only and name not in only:
            continue
        log(f"{name} ...")
        for fname, data, cols in fn(reg, quick, workers):
            w(fname, data, cols)
    man = manifest(
        R.path(),
        workers,
        {
            "mode": "QUICK" if quick else "full",
            "frozen_file": os.path.basename(PT.frozen_path(quick)),
            "registry_hash": config_hash(reg),
            "files": sorted(os.path.basename(p) for p in files.values()),
            "n_loop_runs": len(rows),
            "wall_total_s": time.perf_counter() - t0,
            "seeds": {k: v for k, v in reg["seeds"].items()},
            "max_identity_residual": max([r["max_identity_residual"] for r in rows] or [0.0]),
            "max_violation": max([r["max_violation"] for r in rows] or [0.0]),
            "status_counts": {
                k: int(sum(r[f"n_{k}"] for r in rows)) for k in ("optimal", "inaccurate", "failed")
            },
            "validated_runs": int(sum(1 for r in rows if r.get("validated"))),
        },
    )
    write_json(os.path.join(out_dir, f"manifest{tag}.json"), man)
    log(f"done in {time.perf_counter() - t0:.0f} s")
    return {"files": files, "rows": rows}


def mean_or_nan(xs):
    xs = [x for x in xs if x is not None and math.isfinite(x)]
    return sum(xs) / len(xs) if xs else math.nan
